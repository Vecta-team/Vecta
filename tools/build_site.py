"""Finish the site: icons, manifest, and an offline service worker that pre-saves
every page, script, font and built-in lesson. Run after build_lessons.py."""
import os, json, hashlib
from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.join(HERE, "..", "site")

def icon(px):
    s = 4  # draw big, shrink for smooth edges
    im = Image.new("RGBA", (px * s, px * s), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    W = px * s
    d.rounded_rectangle([0, 0, W - 1, W - 1], radius=int(W * 0.22), fill=(31, 95, 214, 255))
    # faint squared paper
    for i in range(1, 6):
        v = int(W * i / 6)
        d.line([(v, int(W * .08)), (v, int(W * .92))], fill=(255, 255, 255, 38), width=max(1, W // 160))
        d.line([(int(W * .08), v), (int(W * .92), v)], fill=(255, 255, 255, 38), width=max(1, W // 160))
    # the V: a drawn stroke
    lw = int(W * 0.105)
    d.line([(W * .28, W * .28), (W * .5, W * .72), (W * .72, W * .28)], fill="white", width=lw, joint="curve")
    for (x, y) in [(W * .28, W * .28), (W * .72, W * .28), (W * .5, W * .72)]:
        d.ellipse([x - lw / 2, y - lw / 2, x + lw / 2, y + lw / 2], fill="white")
    return im.resize((px, px), Image.LANCZOS)

os.makedirs(os.path.join(SITE, "icons"), exist_ok=True)
for px in (192, 512):
    icon(px).save(os.path.join(SITE, "icons", f"icon-{px}.png"), optimize=True)

manifest = {
    "name": "Vecta Academy", "short_name": "Vecta", "start_url": "./", "scope": "./", "display": "standalone",
    "background_color": "#eef1f5", "theme_color": "#1f5fd6",
    "description": "Sharp maths and science lessons that use a fraction of video's data.",
    "icons": [{"src": "icons/icon-192.png", "sizes": "192x192", "type": "image/png"},
              {"src": "icons/icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any maskable"}],
}
json.dump(manifest, open(os.path.join(SITE, "manifest.webmanifest"), "w"), indent=1)

files, lesson_files = [], []
for root, _, names in os.walk(SITE):
    for n in sorted(names):
        rel = os.path.relpath(os.path.join(root, n), SITE).replace(os.sep, "/")
        if rel in ("sw.js", "README.md") or rel.startswith(".") or rel.endswith("LICENSE"):
            continue
        # Lesson files (lesson.json + audio) are saved when the student taps
        # "Download all lessons" or plays a lesson, not on the first visit.
        (lesson_files if rel.startswith("lessons/") and rel != "lessons/index.json" else files).append(rel)
files.sort(); lesson_files.sort()

def digest(paths):
    h = hashlib.sha1()
    for f in paths:
        h.update(f.encode()); h.update(open(os.path.join(SITE, f), "rb").read())
    return h.hexdigest()[:10]
version, lessons_version = digest(files), digest(lesson_files)
precache = ["./"] + files

sw = f"""/* Vecta offline support. Generated by build_site.py. */
const CACHE = "vecta-app-{version}";          // the app itself: saved on the first visit
const LESSONS = "vecta-lessons-{lessons_version}";  // lessons: saved by "Download all lessons" or when played
const FILES = {json.dumps(precache, indent=1)};

self.addEventListener("install", e => {{
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
}});
self.addEventListener("activate", e => {{
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE && k !== LESSONS).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
}});

// Audio players ask for byte ranges; serve them from a saved whole file.
async function partial(req, res) {{
  const buf = await res.arrayBuffer(), n = buf.byteLength;
  const m = /bytes=(\\d*)-(\\d*)/.exec(req.headers.get("range") || "");
  let a = 0, b = n - 1;
  if (m) {{
    if (m[1] === "" && m[2] !== "") a = Math.max(0, n - Number(m[2]));
    else {{ a = Number(m[1] || 0); if (m[2] !== "") b = Math.min(Number(m[2]), n - 1); }}
  }}
  if (a >= n) return new Response(null, {{ status: 416, headers: {{ "Content-Range": "bytes */" + n }} }});
  return new Response(buf.slice(a, b + 1), {{ status: 206, headers: {{
    "Content-Type": res.headers.get("Content-Type") || "application/octet-stream",
    "Content-Range": "bytes " + a + "-" + b + "/" + n, "Content-Length": String(b - a + 1), "Accept-Ranges": "bytes" }} }});
}}

self.addEventListener("fetch", e => {{
  const req = e.request, url = new URL(req.url);
  if (req.method !== "GET" || url.origin !== location.origin) return;
  url.search = "";
  const isLesson = url.pathname.includes("/lessons/") && !url.pathname.endsWith("/lessons/index.json");
  e.respondWith((async () => {{
    const hit = await caches.match(url.href);
    if (hit) return req.headers.has("range") ? partial(req, hit) : hit;
    if (isLesson) {{
      // Fetch the whole file once, save it, then answer (ranges included) from the saved copy.
      const res = await fetch(url.href);
      if (res.status === 200) {{
        await (await caches.open(LESSONS)).put(url.href, res.clone());
        return req.headers.has("range") ? partial(req, res) : res;
      }}
      return res;
    }}
    return fetch(req);
  }})());
}});
"""
open(os.path.join(SITE, "sw.js"), "w").write(sw)
app = sum(os.path.getsize(os.path.join(SITE, f)) for f in files)
print(f"{len(files)} app files saved on first visit ({app/1000:.0f} KB), version {version}")
print(f"{len(lesson_files)} lesson files saved on download, version {lessons_version}")
